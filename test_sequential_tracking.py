"""
Test Sequential Multi-Camera Tracking with TCM
Simulates scenario: Track vehicle from Camera A -> Camera B
Shows TCM filtering efficiency for temporal tracking
"""

import os
import sys
import time
import datetime
import pickle
import torch
import numpy as np
from pathlib import Path
import argparse
from tqdm import tqdm

# Add project root to path
project_root = Path(__file__).parent
sys.path.append(str(project_root))

# TransReID imports
from config import cfg
from datasets import make_dataloader
from model import make_model
from utils.logger import setup_logger
from utils.metrics import eval_func

# TCM imports  
from utils.veri_camera_config import get_veri_camera_positions
from utils.rule_based_tcm_v2 import RuleBasedTCMV2
from create_realistic_veri_simulation import VeRiCameraNetwork

class SequentialTrackingEvaluator:
    def __init__(self, cfg, model, val_loader, num_query, logger):
        self.cfg = cfg
        self.model = model
        self.val_loader = val_loader
        self.num_query = num_query
        self.logger = logger
        self.device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
        self.model.to(self.device)
        
        # Initialize VeRiCameraNetwork for per-pair travel windows
        self.camera_network = VeRiCameraNetwork()
        
        # Load realistic timestamps (generated by create_realistic_veri_simulation.py)
        self.realistic_timestamps = None
        ts_file = 'data/VeRi/realistic_timestamps.pkl'
        if os.path.exists(ts_file):
            with open(ts_file, 'rb') as f:
                self.realistic_timestamps = pickle.load(f)
            self.logger.info(f"Loaded realistic timestamps for {len(self.realistic_timestamps)} images")
        else:
            self.logger.warning(f"No realistic timestamps found at {ts_file}")
            self.logger.warning("Run: python create_realistic_veri_simulation.py")
        
    def extract_features(self):
        """Extract features for query and gallery"""
        start_time = time.time()
        self.logger.info("Extracting features...")
        self.model.eval()
        
        query_features = []
        gallery_features = []
        query_pids = []
        gallery_pids = []
        query_camids = []
        gallery_camids = []
        query_timestamps = []
        gallery_timestamps = []
        query_paths = []
        gallery_paths = []
        
        with torch.no_grad():
            # Process query set
            for batch_idx, (imgs, pids, camids, camids_batch, viewids, img_paths, timestamps) in enumerate(tqdm(self.val_loader, desc="Query features")):
                imgs = imgs.to(self.device)
                camids_batch = camids_batch.to(self.device)
                viewids = viewids.to(self.device)
                
                if self.cfg.TEST.FEAT_NORM == 'yes':
                    features = torch.nn.functional.normalize(
                        self.model(imgs, cam_label=camids_batch, view_label=viewids), 
                        dim=1, p=2
                    )
                else:
                    features = self.model(imgs, cam_label=camids_batch, view_label=viewids)
                
                query_features.append(features.cpu())
                query_pids.extend(pids)
                query_camids.extend(camids)
                # Override with realistic timestamps if available
                if self.realistic_timestamps:
                    ts_list = []
                    for p in img_paths:
                        fname = os.path.basename(p)
                        ts_list.append(self.realistic_timestamps.get(fname, 0))
                    query_timestamps.extend(ts_list)
                else:
                    query_timestamps.extend(timestamps if timestamps is not None else [None] * len(pids))
                query_paths.extend(img_paths)
                
                if batch_idx == 0:  # Only process query once
                    break
            
            # Process gallery set  
            for batch_idx, (imgs, pids, camids, camids_batch, viewids, img_paths, timestamps) in enumerate(tqdm(self.val_loader, desc="Gallery features")):
                if batch_idx == 0:  # Skip query batch
                    continue
                    
                imgs = imgs.to(self.device)
                camids_batch = camids_batch.to(self.device)
                viewids = viewids.to(self.device)
                
                if self.cfg.TEST.FEAT_NORM == 'yes':
                    features = torch.nn.functional.normalize(
                        self.model(imgs, cam_label=camids_batch, view_label=viewids), 
                        dim=1, p=2
                    )
                else:
                    features = self.model(imgs, cam_label=camids_batch, view_label=viewids)
                
                gallery_features.append(features.cpu())
                gallery_pids.extend(pids)
                gallery_camids.extend(camids)
                # Override with realistic timestamps if available
                if self.realistic_timestamps:
                    ts_list = []
                    for p in img_paths:
                        fname = os.path.basename(p)
                        ts_list.append(self.realistic_timestamps.get(fname, 0))
                    gallery_timestamps.extend(ts_list)
                else:
                    gallery_timestamps.extend(timestamps if timestamps is not None else [None] * len(pids))
                gallery_paths.extend(img_paths)
        
        query_features = torch.cat(query_features, dim=0)
        gallery_features = torch.cat(gallery_features, dim=0)
        
        extraction_time = time.time() - start_time
        self.logger.info(f"Feature extraction completed in {extraction_time:.2f}s")
        
        return {
            'query_features': query_features,
            'gallery_features': gallery_features,
            'query_pids': np.array(query_pids),
            'gallery_pids': np.array(gallery_pids),
            'query_camids': np.array(query_camids),
            'gallery_camids': np.array(gallery_camids),
            'query_timestamps': query_timestamps,
            'gallery_timestamps': gallery_timestamps,
            'query_paths': query_paths,
            'gallery_paths': gallery_paths
        }
    
    def simulate_sequential_tracking(self, data_dict):
        """
        Simulate sequential tracking scenario:
        - For each query at Camera A at time T
        - Search for it in Camera B within travel time window
        """
        self.logger.info("\n" + "="*60)
        self.logger.info("SEQUENTIAL TRACKING SIMULATION")
        self.logger.info("="*60)
        
        query_camids = data_dict['query_camids']
        gallery_camids = data_dict['gallery_camids']
        query_timestamps = data_dict['query_timestamps']
        gallery_timestamps = data_dict['gallery_timestamps']
        
        # Group queries and gallery by camera
        unique_cameras = sorted(set(query_camids) | set(gallery_camids))
        self.logger.info(f"Found {len(unique_cameras)} unique cameras")
        
        # For each camera pair A->B, simulate tracking
        tracking_scenarios = []
        
        for cam_a in unique_cameras[:5]:  # Test first 5 cameras as source
            query_mask = query_camids == cam_a
            num_queries_at_a = query_mask.sum()
            
            if num_queries_at_a == 0:
                continue
                
            # Find connected cameras (cameras we can reach from cam_a)
            for cam_b in unique_cameras:
                if cam_a == cam_b:
                    continue
                    
                gallery_mask = gallery_camids == cam_b
                num_gallery_at_b = gallery_mask.sum()
                
                if num_gallery_at_b == 0:
                    continue
                
                # Get per-camera-pair travel time from VeRiCameraNetwork
                min_time, max_time = self.camera_network.get_travel_time(
                    int(cam_a) + 1, int(cam_b) + 1  # 0-indexed -> 1-indexed
                )
                # Add buffer for traffic variability (matches is_temporally_feasible)
                min_time = max(0, min_time - 10)
                max_time = max_time + 30
                
                tracking_scenarios.append({
                    'cam_a': cam_a,
                    'cam_b': cam_b,
                    'num_queries': num_queries_at_a,
                    'num_gallery': num_gallery_at_b,
                    'min_travel': min_time,
                    'max_travel': max_time
                })
        
        self.logger.info(f"\nFound {len(tracking_scenarios)} tracking scenarios (Camera A -> Camera B)")
        
        return tracking_scenarios, data_dict
    
    def apply_temporal_filtering(self, scenario, data_dict):
        """
        Apply TCM filtering for a specific tracking scenario
        Returns: percentage of gallery filtered out
        """
        cam_a = scenario['cam_a']
        cam_b = scenario['cam_b']
        min_time = scenario['min_travel']
        max_time = scenario['max_travel']
        
        query_camids = data_dict['query_camids']
        gallery_camids = data_dict['gallery_camids']
        query_timestamps = data_dict['query_timestamps']
        gallery_timestamps = data_dict['gallery_timestamps']
        
        # Get queries at camera A
        query_mask = query_camids == cam_a
        query_indices = np.where(query_mask)[0]
        
        # Get gallery at camera B
        gallery_mask = gallery_camids == cam_b
        gallery_indices = np.where(gallery_mask)[0]
        
        total_comparisons = len(query_indices) * len(gallery_indices)
        filtered_count = 0
        valid_count = 0
        
        # For each query at camera A
        for q_idx in query_indices:
            q_time = query_timestamps[q_idx] if query_timestamps[q_idx] is not None else 0
            
            # For each gallery at camera B
            for g_idx in gallery_indices:
                g_time = gallery_timestamps[g_idx] if gallery_timestamps[g_idx] is not None else 0
                
                # Check temporal constraint
                time_diff = g_time - q_time
                
                # TCM filtering: Keep only if within travel time window
                if min_time <= time_diff <= max_time:
                    valid_count += 1
                else:
                    filtered_count += 1
        
        filter_rate = (filtered_count / total_comparisons * 100) if total_comparisons > 0 else 0
        
        return {
            'total_comparisons': total_comparisons,
            'filtered': filtered_count,
            'valid': valid_count,
            'filter_rate': filter_rate
        }
    
    def run_tracking_analysis(self):
        """Run complete sequential tracking analysis"""
        self.logger.info("="*60)
        self.logger.info("SEQUENTIAL MULTI-CAMERA TRACKING WITH TCM")
        self.logger.info("="*60)
        
        # Extract features
        data_dict = self.extract_features()
        
        # Simulate tracking scenarios
        scenarios, data_dict = self.simulate_sequential_tracking(data_dict)
        
        if not scenarios:
            self.logger.info("No tracking scenarios found!")
            return
        
        # Analyze top scenarios
        self.logger.info("\n" + "="*60)
        self.logger.info("ANALYZING TRACKING SCENARIOS")
        self.logger.info("="*60)
        
        total_stats = {
            'total_comparisons': 0,
            'total_filtered': 0,
            'total_valid': 0
        }
        
        # Test top 10 scenarios with most gallery images
        top_scenarios = sorted(scenarios, key=lambda x: x['num_gallery'], reverse=True)[:10]
        
        for i, scenario in enumerate(top_scenarios, 1):
            self.logger.info(f"\n--- Scenario {i}: Camera {scenario['cam_a']} -> Camera {scenario['cam_b']} ---")
            self.logger.info(f"Queries at Camera {scenario['cam_a']}: {scenario['num_queries']}")
            self.logger.info(f"Gallery at Camera {scenario['cam_b']}: {scenario['num_gallery']}")
            self.logger.info(f"Travel time window: {scenario['min_travel']:.0f}s - {scenario['max_travel']:.0f}s")
            
            # Apply TCM filtering
            stats = self.apply_temporal_filtering(scenario, data_dict)
            
            self.logger.info(f"Total comparisons: {stats['total_comparisons']:,}")
            self.logger.info(f"TCM filtered out: {stats['filtered']:,} ({stats['filter_rate']:.2f}%)")
            self.logger.info(f"Valid candidates: {stats['valid']:,} ({100-stats['filter_rate']:.2f}%)")
            
            # Accumulate stats
            total_stats['total_comparisons'] += stats['total_comparisons']
            total_stats['total_filtered'] += stats['filtered']
            total_stats['total_valid'] += stats['valid']
        
        # Overall summary
        self.logger.info("\n" + "="*60)
        self.logger.info("OVERALL TCM FILTERING EFFICIENCY")
        self.logger.info("="*60)
        
        overall_filter_rate = (total_stats['total_filtered'] / total_stats['total_comparisons'] * 100) \
            if total_stats['total_comparisons'] > 0 else 0
        
        self.logger.info(f"Total comparisons: {total_stats['total_comparisons']:,}")
        self.logger.info(f"Filtered by TCM: {total_stats['total_filtered']:,} ({overall_filter_rate:.2f}%)")
        self.logger.info(f"Valid candidates: {total_stats['total_valid']:,} ({100-overall_filter_rate:.2f}%)")
        self.logger.info("")
        self.logger.info(f"TCM reduces search space by {overall_filter_rate:.2f}%")
        self.logger.info(f"Speedup potential: {100/(100-overall_filter_rate):.1f}x fewer comparisons")


def main():
    parser = argparse.ArgumentParser(description="Test Sequential Tracking with TCM")
    parser.add_argument('--config_file', type=str, 
                       default='configs/VeRi/vit_transreid_stride.yml',
                       help='path to config file')
    parser.add_argument('--model_path', type=str, required=True,
                       help='path to trained model')
    parser.add_argument('--output_dir', type=str, default='logs/sequential_tracking',
                       help='output directory for results')
    parser.add_argument('opts', default=None, nargs=argparse.REMAINDER,
                       help='modify config options using the command-line')
    
    args = parser.parse_args()
    
    # Setup config
    cfg.merge_from_file(args.config_file)
    cfg.merge_from_list(args.opts)
    cfg.freeze()
    
    # Create timestamped output directory
    timestamp = datetime.datetime.now().strftime("%Y-%m-%d_%H-%M-%S")
    output_dir = os.path.join(args.output_dir, timestamp)
    os.makedirs(output_dir, exist_ok=True)
    
    # Setup logger
    logger = setup_logger('sequential_tracking', output_dir, if_train=False)
    logger.info(f"Config: {args.config_file}")
    logger.info(f"Model: {args.model_path}")
    
    # Create dataloader first to get camera and view numbers
    train_loader, train_loader_normal, val_loader, num_query, num_classes, camera_num, view_num = make_dataloader(cfg)
    
    # Create model with correct camera and view numbers
    model = make_model(cfg, num_class=num_classes, camera_num=camera_num, view_num=view_num)
    model.load_param(args.model_path)
    
    logger.info(f"Model loaded: {args.model_path}")
    logger.info(f"Dataset: {cfg.DATASETS.NAMES} with {num_classes} identities")
    
    # Run tracking analysis
    evaluator = SequentialTrackingEvaluator(cfg, model, val_loader, num_query, logger)
    evaluator.run_tracking_analysis()
    
    logger.info(f"\nResults saved to: {args.output_dir}")


if __name__ == '__main__':
    main()
